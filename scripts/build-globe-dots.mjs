// Builds the land mask for the flight globe (src/data/globe-land.ts).
// Points sit on a Fibonacci sphere; one bit per point says whether it is on land
// (Natural Earth 110m via world-atlas). The browser rebuilds the same points from N,
// so the shipped data is a ~2 KB base64 bitset instead of thousands of coordinates.
// Run: node scripts/build-globe-dots.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';
import { geoContains } from 'd3-geo';

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = feature(topo, topo.objects.land);

const N = 12000;
const golden = Math.PI * (3 - Math.sqrt(5));
const bits = new Uint8Array(Math.ceil(N / 8));
let count = 0;
for (let i = 0; i < N; i++) {
  const y = 1 - (2 * (i + 0.5)) / N; // keep in sync with flight-globe.ts
  const lat = (Math.asin(y) * 180) / Math.PI;
  let lon = ((((i * golden) * 180) / Math.PI) % 360);
  if (lon > 180) lon -= 360;
  if (lat < -60) continue; // leave Antarctica out, it only adds noise at the bottom
  if (geoContains(land, [lon, lat])) {
    bits[i >> 3] |= 1 << (i & 7);
    count++;
  }
}

const b64 = Buffer.from(bits).toString('base64');
writeFileSync(
  new URL('../src/data/globe-land.ts', import.meta.url),
  `// Generated by scripts/build-globe-dots.mjs from Natural Earth 110m land (public domain). Do not edit.\n` +
    `export const LAND_POINTS = ${N};\nexport const LAND_MASK = '${b64}';\n`,
);
console.log(`land points: ${count} of ${N}, mask ${b64.length} chars`);
